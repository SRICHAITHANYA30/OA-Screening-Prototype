    def translate(self, key: str, language: str | None = None) -> str:
        lang = (language or self.default_language).lower()
        bundle = self.translations.get(lang, self.translations["en"])
        return bundle.get(key, self.translations["en"].get(key, key))

    def bundle(self, language: str | None = None) -> dict[str, str]:
        lang = (language or self.default_language).lower()
        return self.translations.get(lang, self.translations["en"]) 
